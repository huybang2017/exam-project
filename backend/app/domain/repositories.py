"""Giao diện repository và Unit of Work. Cài đặt nằm ở infrastructure/db."""
from datetime import datetime
from typing import Protocol, Self

from app.domain.entities import (
    Attempt,
    Exam,
    ExamResultRow,
    GradeInputs,
    PublicQuestion,
    Question,
    User,
)


class UserRepository(Protocol):
    async def get(self, user_id: int) -> User | None: ...
    async def get_by_username(self, username: str) -> User | None: ...
    async def add(self, user: User) -> User:
        """Ném ConflictError("Tên đăng nhập đã tồn tại") nếu trùng username."""
        ...
    async def list(self, role: str | None, skip: int, limit: int) -> tuple[int, list[User]]: ...
    async def count(self) -> int: ...


class QuestionRepository(Protocol):
    async def add(self, question: Question) -> Question: ...
    async def get(self, question_id: int) -> Question | None: ...
    async def search(self, text: str | None, skip: int, limit: int) -> tuple[int, list[Question]]: ...
    async def delete(self, question_id: int) -> None: ...
    async def is_used_in_exam(self, question_id: int) -> bool: ...
    async def count_existing(self, question_ids: list[int]) -> int: ...


class ExamRepository(Protocol):
    async def add(self, exam: Exam) -> Exam: ...
    async def get(self, exam_id: int) -> Exam | None:
        """Kèm danh sách items."""
        ...
    async def list_for(self, user: User) -> list[Exam]:
        """Sinh viên: đề đã công bố; giáo viên: đề của mình; admin: tất cả (mới nhất trước)."""
        ...
    async def save(self, exam: Exam) -> None: ...
    async def questions_with_answers(self, exam_id: int) -> list[Question]: ...
    async def public_questions(self, exam_id: int) -> tuple[PublicQuestion, ...]: ...
    async def valid_choice_pairs(self, exam_id: int, choice_ids: list[int]) -> set[tuple[int, int]]:
        """Tập (choice_id, question_id) hợp lệ thuộc đề."""
        ...


class AttemptRepository(Protocol):
    async def add(self, attempt: Attempt) -> Attempt:
        """Ném DuplicateAttemptError nếu vi phạm UNIQUE(exam_id, user_id)."""
        ...
    async def get(self, attempt_id: int) -> Attempt | None: ...
    async def get_for_exam_user(self, exam_id: int, user_id: int) -> Attempt | None: ...
    async def list_for_user(self, user_id: int) -> list[Attempt]: ...
    async def save(self, attempt: Attempt) -> None: ...
    async def saved_answers(self, attempt_id: int) -> dict[int, int]: ...
    async def upsert_answers(self, attempt_id: int, answers: dict[int, int]) -> None: ...
    async def grade_inputs(self, attempt: Attempt) -> GradeInputs: ...
    async def list_expired(self, now: datetime) -> list[Attempt]: ...
    async def results_for_exam(self, exam_id: int) -> list[ExamResultRow]: ...


class UnitOfWork(Protocol):
    users: UserRepository
    questions: QuestionRepository
    exams: ExamRepository
    attempts: AttemptRepository

    async def __aenter__(self) -> Self: ...
    async def __aexit__(self, *exc) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...
